param([string] $OutputDirectory)
if (-not $OutputDirectory) { $OutputDirectory = Join-Path (Split-Path -Parent (Split-Path -Parent $PSScriptRoot)) '.runtime\store-media' }
$ErrorActionPreference = 'Stop'
[void][IO.Directory]::CreateDirectory($OutputDirectory)
Add-Type -AssemblyName System.Drawing
if (-not ('ClearCastOriginalStoreArtwork' -as [type])) {
    Add-Type -ReferencedAssemblies @([System.Drawing.Bitmap].Assembly.Location, [System.Drawing.Color].Assembly.Location,
        (Join-Path (Split-Path -Parent ([System.Drawing.Bitmap].Assembly.Location)) 'System.Private.Windows.GdiPlus.dll'),
        (Join-Path (Split-Path -Parent ([System.Drawing.Bitmap].Assembly.Location)) 'System.Private.Windows.Core.dll')) -TypeDefinition @'
using System;
using System.Drawing;
using System.Drawing.Imaging;
public static class ClearCastOriginalStoreArtwork {
    static double Clamp(double value) { return Math.Max(0, Math.Min(1, value)); }
    static double Smooth(double from, double to, double value) {
        double t = Clamp((value-from)/(to-from)); return t*t*(3-2*t);
    }
    static double Bell(double value, double width) { return Math.Exp(-value*value/(2*width*width)); }
    static void Mix(ref double r, ref double g, ref double b, double nr, double ng, double nb, double weight) {
        weight=Clamp(weight); r+=(nr-r)*weight; g+=(ng-g)*weight; b+=(nb-b)*weight;
    }
    public static void Save(string path) {
        const int size=768;
        using (var image=new Bitmap(size,size,PixelFormat.Format32bppArgb)) {
            for(int y=0;y<size;y++) for(int x=0;x<size;x++) {
                double u=(x+.5)/size,v=(y+.5)/size;
                double r=23,g=49,b=68;
                double sky=(1-Smooth(.2,.82,v))*(.78+.22*Math.Cos(u*2.2));
                Mix(ref r,ref g,ref b,237,210,173,sky);
                double copper=Bell(v-(.33+.17*Math.Sin(u*3.4-.7)),.19)*(1-Smooth(.55,1,u));
                Mix(ref r,ref g,ref b,195,112,79,copper*.80);
                double deep=Smooth(.32,.6,v+.12*Math.Sin(u*4.3+.4));
                Mix(ref r,ref g,ref b,27,60,78,deep*.88);
                double river=Bell(v-(.61+.145*Math.Sin(u*4.2-1.1)),.074);
                Mix(ref r,ref g,ref b,73,161,156,river*.95);
                double brightRiver=Bell(v-(.588+.145*Math.Sin(u*4.2-1.1)),.015);
                Mix(ref r,ref g,ref b,152,198,178,brightRiver*.65);
                double ribbon=Bell(v-(.31+.085*Math.Sin(u*5.0+.8)),.028);
                Mix(ref r,ref g,ref b,236,179,97,ribbon*.88);
                double shadow=Bell(v-(.82+.10*Math.Sin(u*3.8+.4)),.12);
                Mix(ref r,ref g,ref b,18,39,62,shadow*.72);
                double paper=(Math.Sin(u*137+v*97)+Math.Sin(u*83-v*119))*.40;
                image.SetPixel(x,y,Color.FromArgb(255,(int)Math.Round(Math.Max(0,Math.Min(255,r+paper))),
                    (int)Math.Round(Math.Max(0,Math.Min(255,g+paper))),(int)Math.Round(Math.Max(0,Math.Min(255,b+paper)))));
            }
            image.Save(path,ImageFormat.Png);
        }
    }
}
'@
}
$cover = Join-Path ([IO.Path]::GetFullPath($OutputDirectory)) 'clearcast-original-music-cover.png'
[ClearCastOriginalStoreArtwork]::Save($cover)
$report = [ordered]@{
    source = 'Original deterministic geometric artwork generated by this repository QA script; no reference photograph, album cover, logo or third-party asset.'
    generator = [IO.Path]::GetFullPath($PSCommandPath)
    artwork = $cover
    sha256 = (Get-FileHash -LiteralPath $cover -Algorithm SHA256).Hash
    width = 768
    height = 768
    alpha = 'Opaque 255 for every pixel'
    metadata = 'All track and album names shown by the store screenshot harness are fictional demonstration metadata; no music recording is distributed.'
    productionAsset = $false
}
$report | ConvertTo-Json -Depth 4 | Set-Content -LiteralPath (Join-Path $OutputDirectory 'artwork-provenance.json') -Encoding utf8NoBOM
$report | ConvertTo-Json -Depth 4
